'use strict';
const { spawn } = require('node:child_process');
const path = require('node:path');
const root = path.join(__dirname, '..');
const packaged = process.argv.includes('--packaged');
const executable = packaged ? path.join(root, 'Aula Fantasma.exe') : process.env.AULA_ELECTRON_EXE || require('electron');
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const args = ['--smoke-test', `--smoke-legacy=${path.join(root, 'tests', 'fixtures', 'EduScream-v3.aulapet')}`, `--smoke-frank-legacy=${path.join(root, 'tests', 'fixtures', 'EduFrankenstein-original.aulapet')}`];
if (process.argv.includes('--panel-only')) args.push('--smoke-panel');
if (process.argv.includes('--voice')) args.push('--smoke-voice');
if (process.argv.includes('--kimi')) args.push('--smoke-voice', '--smoke-kimi');
if (process.argv.includes('--catrin')) args.push('--smoke-voice', '--smoke-catrin');
if (process.argv.includes('--catrina')) args.push('--smoke-voice', '--smoke-catrina');
if (process.argv.includes('--geometry')) args.push('--smoke-voice', '--smoke-geometry');
if (process.argv.includes('--opacity')) args.push('--smoke-voice', '--smoke-opacity');
if (process.argv.includes('--dracula')) args.push('--smoke-voice', '--smoke-dracula');
if (process.argv.includes('--zombie')) args.push('--smoke-zombie');
if (process.argv.includes('--vehicle')) args.push('--smoke-vehicle');
if (process.argv.includes('--real-microphone')) args.push('--real-microphone');
if (process.argv.includes('--sandbox-workaround')) args.push('--no-sandbox', '--disable-gpu');
const child = spawn(executable, packaged ? args : [root, ...args], { cwd: root, stdio: 'inherit', env, windowsHide: true });
const timeout = setTimeout(() => { console.error('La prueba de arranque excedió 120 segundos.'); child.kill(); process.exitCode = 1; }, 120000);
child.on('error', error => { clearTimeout(timeout); console.error(error); process.exitCode = 1; });
child.on('exit', code => { clearTimeout(timeout); process.exitCode = code ?? 1; });
