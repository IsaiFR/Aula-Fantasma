function hairAnimation(name, base) {
  const motionRegions = hairstyles[name].map((points, index) => ({
    feather: index === 0 ? .027 : .021,
    strength: index === 0 ? .8 : 1,
    points: points.map(([x, y]) => [x / 420, y / 420])
  }));
  return animationProfile({ ...base, cloth: {
    enabled: true, motionRegions,
    amplitudeX: .013, amplitudeX2: .005, amplitudeY: .012,
    frequencyY: 15, speedX: 2.1, frequencyX2: 12, frequencyY2: 8, speedX2: 2.55,
    frequencyX: 12, frequencyY3: 8, speedY: 2.3
  } });
}

if (require.main === module) {
  for (const name of Object.keys(hairstyles)) {
    const filename = path.join(__dirname, '..', 'pets', `${name}-Voz.pet`);
    const original = parsePet(fs.readFileSync(filename));
    const updated = serializePet({ ...original, animation: hairAnimation(name, original.animation) });
    fs.writeFileSync(filename, updated);
    console.log(`${name} · cabello animado`);
  }
}

