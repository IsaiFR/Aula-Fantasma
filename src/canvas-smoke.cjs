'use strict';
const fs = require('node:fs'), path = require('node:path');
module.exports = async function(c) {
  const { panel, microphoneWindow, snapshot, savePreferences, loadPreferences, notify, smokeRoot, wait } = c;
  const checks = {};
  const js = code => panel.webContents.executeJavaScript(code);
  const choose = async (type, name) => {
    await js(`window.aula.editType(${JSON.stringify(type)})`);
    const library = await js('window.aula.getPetLibrary()'), pet = library.pets.find(p=>p.name===name);
    if (!pet) throw new Error('Falta el personaje del perfil de prueba.');
    const result = await js(`window.aula.selectPet(${JSON.stringify(pet.id)})`); if (result.error) throw new Error(result.error);
  };
  await js('window.aula.setCanvasFormat("16:9");');
  await choose('voice','EduGhost (voz)');
  await js('window.aula.setSettings({size:260,corner:"bottom-right",opacity:96,micEnabled:true},"voice")');
  await js('window.aula.setSettings({mode:"free",size:180,speed:45,booInterval:20,presenceEnabled:false},"companion")');
  await wait(()=>snapshot().microphone.status==='active','Micrófono antes del cambio');
  await microphoneWindow.webContents.executeJavaScript(`window.canvasCaptureCalls=0;window.canvasOriginalCapture=navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);navigator.mediaDevices.getUserMedia=(...args)=>{window.canvasCaptureCalls++;return window.canvasOriginalCapture(...args);};void 0`);
  const landscape = snapshot();
  await js('document.getElementById("canvas-portrait").click();void 0'); await wait(()=>snapshot().canvas.format==='9:16','Lienzo vertical');
  await choose('voice','EduMomia (voz)');
  await js('window.aula.setSettings({size:190,corner:"top-left",opacity:88},"voice")');
  await js('window.aula.setSettings({mode:"edges",size:120,speed:28,booInterval:50},"companion")');
  const portrait = snapshot();
  checks.portraitPreview = await js(`(() => {const r=document.getElementById('preview').getBoundingClientRect();return Math.abs(r.width/r.height-9/16)<.002 && document.getElementById('canvas-portrait').getAttribute('aria-pressed')==='true';})()`);
  checks.portraitFitsWindow = await js(`(() => {const r=document.getElementById('preview').getBoundingClientRect();return r.bottom+scrollY<=innerHeight && document.documentElement.scrollWidth<=innerWidth;})()`);
  checks.portraitReference = portrait.canvas.width===1080 && portrait.canvas.height===1920;
  await js('window.scrollTo(0,0);new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  fs.writeFileSync(path.join(smokeRoot,'canvas-portrait.png'),(await panel.webContents.capturePage()).toPNG());
  Object.assign(checks, await require('./canvas-geometry-smoke.cjs')(c));
  await js('document.getElementById("canvas-landscape").click();void 0'); await wait(()=>snapshot().canvas.format==='16:9','Lienzo horizontal');
  let state = snapshot();
  checks.canvasProfilesIndependent = state.companions.voice.id===landscape.companions.voice.id && state.settings.size===260 && state.settings.corner==='bottom-right' && state.settings.opacity===96;
  await js('window.aula.editType("companion")'); state=snapshot();
  checks.canvasMovementRestored = state.settings.size===180 && state.settings.speed===45 && state.settings.mode==='free' && state.settings.booInterval===20;
  for (let i=0;i<6;i++) await js(`window.aula.setCanvasFormat(${JSON.stringify(i%2?'16:9':'9:16')})`);
  checks.canvasNoMicRestart = snapshot().microphone.status==='active' && (await microphoneWindow.webContents.executeJavaScript('window.canvasCaptureCalls'))===0;
  const invalid = await js('window.aula.setCanvasFormat("4:3").then(()=>false,()=>true)'); checks.invalidCanvasRejected=invalid && snapshot().canvas.format==='16:9';
  await js('window.aula.setSettings({micEnabled:false},"voice")');
  savePreferences(); const savedBytes=fs.readFileSync(path.join(smokeRoot,'settings.json'));
  loadPreferences(); notify(); await js('window.aula.setCanvasFormat("9:16")'); state=snapshot();
  checks.canvasSurvivesReload = state.canvas.format==='9:16' && state.companions.voice.id===portrait.companions.voice.id && state.settings.size===190 && state.settings.corner==='top-left' && state.settings.opacity===88 && !state.settings.micEnabled;
  await js('window.aula.editType("companion")'); state=snapshot(); checks.canvasPortraitMovementSaved=state.settings.size===120 && state.settings.speed===28 && state.settings.booInterval===50;
  fs.writeFileSync(path.join(smokeRoot,'settings.json'),savedBytes); loadPreferences(); notify();
  await js('window.aula.editType("voice")');
  await microphoneWindow.webContents.executeJavaScript('navigator.mediaDevices.getUserMedia=window.canvasOriginalCapture;void 0');
  return checks;
};
