'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
module.exports=async function(c) {
  const {panel,views,motion,notify,wait,root,smokeRoot}=c,checks={};
  const js=code=>panel.webContents.executeJavaScript(code),before=c.snapshot();
  const ghost=c.parsePet(fs.readFileSync(path.join(root,'pets','EduGhost-Voz.pet')));
  const inspect=`(() => {const d=document.getElementById('voice-layer')?.contentDocument,a=d?.getElementById('pet-anchor');return a?{opacity:Number(getComputedStyle(a).opacity),phase:a.dataset.opacityPhase}:{};})()`;
  const waitOpacity=async (opacity,phase)=>wait(async()=> (await Promise.all(views.map(v=>v.webContents.executeJavaScript(inspect)))).every(s=>Math.abs(s.opacity-opacity)<.001 && s.phase===phase),`Transparencia ${phase}`);
  await js('window.aula.editType("voice")');
  checks.ghostReplacesOpacityControls=await js(`!document.getElementById('ghost-opacity-card').hidden && document.getElementById('manual-opacity-controls').hidden && document.getElementById('opacity').disabled`);
  checks.ghostControlsBelowObs=await js(`(() => {const card=document.getElementById('ghost-opacity-card'),obs=document.querySelector('.obs-card');return card.parentElement===obs.parentElement && card.getBoundingClientRect().top>=obs.getBoundingClientRect().bottom;})()`);
  await js('window.aula.setSettings({paused:true,opacity:20,ghostSolidSeconds:2,ghostFadedSeconds:2},"voice")');
  await js(`(() => {const s=document.getElementById('ghostSolidSeconds-value');s.value='1';s.dispatchEvent(new Event('change',{bubbles:true}));const f=document.getElementById('ghostFadedSeconds');f.value='1';f.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  await wait(()=>c.snapshot().settings.ghostSolidSeconds===1 && c.snapshot().settings.ghostFadedSeconds===1,'Controles de tiempo');
  checks.ghostSecondsControls=await js(`document.getElementById('ghostSolidSeconds').value==='1' && document.getElementById('ghostFadedSeconds-value').value==='1'`);
  const base=motion.elapsed;
  for(const [time,opacity,phase] of [[0,1,'solid'],[1.4,.875,'fading-out'],[1.9,.75,'faded'],[3.2,.875,'fading-in'],[3.6,1,'solid']]) {
    motion.elapsed=base+time;notify();await waitOpacity(opacity,phase);
  }
  checks.ghostOpacitySynchronizedOnAllSurfaces=true;
  checks.ghostOverridesOldManualOpacity=c.getFrame().settings.opacity===20 && c.getFrame().ghostOpacity.opacity===1;
  motion.elapsed=base;notify();
  await js('window.aula.setSettings({paused:true},"companion");window.aula.setSettings({paused:false},"voice")');
  await waitOpacity(.75,'faded'); await waitOpacity(1,'solid');
  checks.ghostOpacityRepeatsWhileCompanionPaused=true;
  await js('window.aula.setSettings({paused:true},"voice")');
  const frozen=c.getFrame().ghostOpacity;
  await new Promise(r=>setTimeout(r,180));assert.deepEqual(c.getFrame().ghostOpacity,frozen);
  checks.ghostOpacityUsesCharacterClock=true;
  await js('window.aula.resetPosition()');
  checks.ghostResetStartsAt100=c.getFrame().ghostOpacity.opacity===1 && c.getFrame().ghostOpacity.phase==='solid';
  c.savePreferences();c.loadPreferences();notify();
  checks.ghostTimesSurviveReload=c.snapshot().settings.ghostSolidSeconds===1 && c.snapshot().settings.ghostFadedSeconds===1 && Boolean(c.getFrame().ghostOpacity);
  const format=c.snapshot().canvas.format,other=format==='16:9'?'9:16':'16:9';
  await js(`window.aula.setCanvasFormat(${JSON.stringify(other)})`);
  c.activatePet(ghost,true);
  await js('window.aula.setSettings({ghostSolidSeconds:3,ghostFadedSeconds:4},"voice")');
  await js(`window.aula.setCanvasFormat(${JSON.stringify(format)})`);
  const restored=c.snapshot();
  checks.ghostTimesIndependentByCanvas=restored.settings.ghostSolidSeconds===1 && restored.settings.ghostFadedSeconds===1;
  c.activatePet(c.parsePet(fs.readFileSync(path.join(root,'pets','EduWitch-Voz.pet'))),false);
  await js('window.aula.setSettings({opacity:63},"voice")');notify();
  await waitOpacity(.63,'manual');
  checks.otherPetsKeepManualOpacity=await js(`document.getElementById('ghost-opacity-card').hidden && !document.getElementById('manual-opacity-controls').hidden && !document.getElementById('opacity').disabled`);
  checks.movingGhostHasNoOpacityCycle=!c.getCompanionFrame().ghostOpacity;
  c.activatePet(ghost,true);await js(`window.aula.setSettings(${JSON.stringify(before.settings)},"voice")`);
  await wait(()=>js(`!document.getElementById('ghost-opacity-card').hidden`),'Panel de transparencia');
  await js('document.getElementById("ghost-opacity-card").scrollIntoView({block:"center"});new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  fs.writeFileSync(path.join(smokeRoot,'ghost-opacity-panel.png'),(await panel.webContents.capturePage()).toPNG());
  return checks;
};
